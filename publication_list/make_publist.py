#!/usr/bin/env python3
"""Generate entries.tex from publications.bib.

Run:  python3 make_publist.py
Then compile publication_list.tex.

Sections: journal articles, conference papers, preprints (@misc).
Within a section, entries keep the order of the bib file (newest first) and are
numbered downwards, so the highest number is the most recent paper.
"""
import re
from pathlib import Path

HERE = Path(__file__).parent
BIB = HERE / "publications.bib"
OUT = HERE / "entries.tex"
ME = "S. Szufa"


def parse_bib(text):
    text = re.sub(r"(?m)^\s*%.*$", "", text)  # strip comment lines
    strings, entries = {}, []
    for m in re.finditer(r"@(\w+)\s*\{", text):
        kind = m.group(1).lower()
        # find the matching closing brace
        depth, i = 1, m.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        body = text[m.end():i - 1]
        if kind == "string":
            k, v = body.split("=", 1)
            strings[k.strip()] = v.strip().strip("{}")
            continue
        key, _, fields = body.partition(",")
        entry = {"type": kind, "key": key.strip()}
        for name, val in parse_fields(fields, strings):
            entry[name] = re.sub(r"\s+", " ", val.strip())
        entries.append(entry)
    return entries


def parse_fields(s, strings):
    """Yield (name, value) pairs; values may contain nested braces."""
    i = 0
    while True:
        m = re.compile(r"\s*(\w+)\s*=\s*").match(s, i)
        if not m:
            return
        name, i = m.group(1).lower(), m.end()
        if s[i] == "{":
            depth, j = 1, i + 1
            while depth:
                depth += {"{": 1, "}": -1}.get(s[j], 0)
                j += 1
            val, i = s[i + 1:j - 1], j
        else:
            m2 = re.compile(r"\w+").match(s, i)
            val, i = strings[m2.group(0)], m2.end()
        yield name, val
        m3 = re.compile(r"\s*,?").match(s, i)
        i = m3.end()


def authors(field):
    names = [a.strip().replace("~", " ") for a in re.split(r"\s+and\s+", field)]
    names = [f"\\textbf{{{a}}}" if a == ME else a for a in names]
    if len(names) == 1:
        return names[0]
    if len(names) == 2:
        return f"{names[0]} and {names[1]}"
    return ", ".join(names[:-1]) + ", and " + names[-1]


def format_entry(e):
    title = e["title"].rstrip(".")
    if not title.endswith(("?", "!")):
        title += "."
    parts = [authors(e["author"]) + ".", title]
    if e["type"] == "article":
        venue = f"\\emph{{{e['journal']}}}"
        if "volume" in e:
            venue += f" {e['volume']}"
        if "pages" in e:
            venue += f", pp.~{e['pages']}"
        parts.append(f"{venue}, {e['year']}.")
    elif e["type"] == "misc":
        parts.append(f"\\emph{{{e['howpublished']}}}, {e['year']}.")
    else:
        venue = f"\\emph{{{e['booktitle']}}}"
        if "pages" in e:
            venue += f", pp.~{e['pages']}"
        parts.append(venue + ".")
    if "url" in e:
        shown = re.sub(r"^https?://", "", e["url"]).rstrip("/")
        parts.append(f"\\href{{{e['url']}}}{{{shown}}}.")
    if "note" in e:
        parts.append(f"{{\\small\\color{{accent}}{e['note']}.}}")
    return " ".join(parts)


def section(title, prefix, items):
    lines = [f"\\section{{{title}}}", "\\begin{itemize}[label={},leftmargin=3.2em,itemsep=2.5pt]"]
    n = len(items)
    for i, e in enumerate(items):
        lines.append(f"\\item[\\textbf{{[{prefix}{n - i}]}}] {format_entry(e)}")
    lines.append("\\end{itemize}")
    return "\n".join(lines)


def main():
    entries = parse_bib(BIB.read_text(encoding="utf-8"))
    journals = [e for e in entries if e["type"] == "article"]
    confs = [e for e in entries if e["type"] not in ("article", "misc")]
    preprints = [e for e in entries if e["type"] == "misc"]
    out = "\n\n".join([
        "% Generated by make_publist.py from publications.bib -- do not edit by hand.",
        section("Journal Articles", "J", journals),
        section("Conference Papers", "C", confs),
        section("Preprints and Manuscripts", "P", preprints),
    ])
    OUT.write_text(out + "\n", encoding="utf-8")
    print(f"{len(journals)} journal, {len(confs)} conference, {len(preprints)} preprint -> {OUT.name}")


if __name__ == "__main__":
    main()
